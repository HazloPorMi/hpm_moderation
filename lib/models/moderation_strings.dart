/// Localization strings for the moderation package.
/// Each app passes its own translated strings from its locale system.
class ModerationStrings {
  final String reportMessage;
  final String reportUser;
  final String blockUser;
  final String unblockUser;
  final String blockedUsers;
  final String blockConfirmTitle;
  final String blockConfirmBody;
  final String blockedSuccessfully;
  final String unblockedSuccessfully;
  final String reportSubmitted;
  final String alreadyReported;
  final String selectReason;
  final String reasonSpam;
  final String reasonHarassment;
  final String reasonInappropriate;
  final String reasonFraud;
  final String reasonOther;
  final String describeIssue;
  final String noBlockedUsers;
  final String blockedOn;
  final String canMessageAgain;
  final String cancel;
  final String report;
  final String yes;
  final String no;
  final String error;

  const ModerationStrings({
    required this.reportMessage,
    required this.reportUser,
    required this.blockUser,
    required this.unblockUser,
    required this.blockedUsers,
    required this.blockConfirmTitle,
    required this.blockConfirmBody,
    required this.blockedSuccessfully,
    required this.unblockedSuccessfully,
    required this.reportSubmitted,
    required this.alreadyReported,
    required this.selectReason,
    required this.reasonSpam,
    required this.reasonHarassment,
    required this.reasonInappropriate,
    required this.reasonFraud,
    required this.reasonOther,
    required this.describeIssue,
    required this.noBlockedUsers,
    required this.blockedOn,
    required this.canMessageAgain,
    required this.cancel,
    required this.report,
    required this.yes,
    required this.no,
    required this.error,
  });
}
